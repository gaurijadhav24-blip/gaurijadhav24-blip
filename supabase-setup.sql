-- Run this in Supabase Dashboard > SQL Editor for your LearnAble project.
-- Public visitors can submit feedback and quiz score summaries, but cannot read rows.
-- For a public production site, consider CAPTCHA/rate limiting to reduce spam.

create table if not exists public.feedback (
  id bigint generated by default as identity primary key,
  name text not null default 'Anonymous' check (char_length(name) <= 100),
  user_type text not null check (user_type in ('Learner', 'Parent', 'Educator', 'Other')),
  rating integer not null check (rating between 1 and 5),
  feedback_text text not null check (char_length(feedback_text) between 1 and 1000),
  suggestions text check (suggestions is null or char_length(suggestions) <= 500),
  created_at timestamptz not null default now()
);

create table if not exists public.activity_scores (
  id bigint generated by default as identity primary key,
  activity_key text not null default 'learning-awareness-quiz',
  correct_answers integer not null check (correct_answers >= 0),
  total_questions integer not null check (total_questions > 0),
  percentage integer not null check (percentage between 0 and 100),
  created_at timestamptz not null default now(),
  constraint activity_score_counts_valid check (correct_answers <= total_questions),
  constraint activity_score_percentage_valid check (percentage = round((correct_answers::numeric / total_questions) * 100))
);

alter table public.feedback enable row level security;
alter table public.activity_scores enable row level security;

-- Re-runnable policy creation: remove these policy names if they already exist.
drop policy if exists "Anyone can submit feedback" on public.feedback;
create policy "Anyone can submit feedback"
  on public.feedback for insert to anon, authenticated
  with check (true);

drop policy if exists "Anyone can submit activity scores" on public.activity_scores;
create policy "Anyone can submit activity scores"
  on public.activity_scores for insert to anon, authenticated
  with check (true);

